from __future__ import annotations

import unittest
from pathlib import Path
from subprocess import CompletedProcess
from unittest.mock import patch

from fastapi import HTTPException

from backend.app import pdf_compare
from backend.app.pdf_compare import _pixel_similarity, _read_ppm, _text_diff


class PdfCompareTests(unittest.TestCase):
    def test_ppm_keeps_whitespace_valued_first_pixel(self):
        width, height, pixels = _read_ppm(b"P6\r\n# generated by Poppler\r\n2 1\r\n255\r\n\x20\x00\x00\xff\x00\x00")
        self.assertEqual((width, height), (2, 1))
        self.assertEqual(pixels, b"\x20\x00\x00\xff\x00\x00")

    def test_rejects_truncated_or_non_binary_ppm(self):
        with self.assertRaises(HTTPException):
            _read_ppm(b"P6\n2 1\n255\n\x00\x00")
        with self.assertRaises(HTTPException):
            _read_ppm(b"P3\n1 1\n255\n0 0 0")

    def test_visual_similarity_uses_per_pixel_noise_threshold(self):
        same = _pixel_similarity((2, 1, b"\x10\x20\x30\xff\x00\x00"), (2, 1, b"\x10\x20\x30\xff\x00\x00"))
        changed = _pixel_similarity((2, 1, b"\x00\x00\x00\x00\x00\x00"), (2, 1, b"\xff\xff\xff\x00\x00\x00"))
        mismatch = _pixel_similarity((1, 1, b"\x00\x00\x00"), (2, 1, b"\x00\x00\x00\x00\x00\x00"))
        self.assertEqual(same["similarity"], 100.0)
        self.assertEqual(changed["similarity"], 50.0)
        self.assertTrue(mismatch["sizeMismatch"])

    def test_text_diff_counts_additions_and_removals(self):
        result = _text_diff("one\nstable\nold\n".encode(), "one\nstable\nnew\nextra\n".encode())
        self.assertEqual((result["added"], result["removed"]), (2, 1))
        self.assertEqual([row["type"] for row in result["changes"]], ["removed", "added", "added"])

    def test_compare_uses_bundled_poppler_for_text_and_page_images(self):
        def run(command, **_kwargs):
            name = Path(command[-1]).name
            if command[0] == "pdfinfo":
                return CompletedProcess(command, 0, b"Pages:  2\n", b"")
            if command[0] == "pdftotext":
                source = Path(command[-2]).read_bytes()
                text = b"contract\nold clause\n" if source == b"left" else b"contract\nnew clause\n"
                return CompletedProcess(command, 0, text, b"")
            if command[0] == "pdftoppm":
                source = Path(command[3]).read_bytes()
                prefix = Path(command[4])
                first_pixel = b"\x00\x00\x00" if source == b"left" else b"\xff\xff\xff"
                second_pixel = b"\x00\x00\x00"
                for page, pixel in ((1, first_pixel), (2, second_pixel)):
                    Path(f"{prefix}-{page}.ppm").write_bytes(b"P6\n1 1\n255\n" + pixel)
                return CompletedProcess(command, 0, b"", b"")
            self.fail(f"Unexpected Poppler command: {command}")

        with patch.object(pdf_compare.subprocess, "run", side_effect=run):
            report = pdf_compare._compare_bytes(b"left", b"right", "left.pdf", "right.pdf")
        self.assertEqual((report["left"]["pages"], report["right"]["pages"]), (2, 2))
        self.assertEqual(report["text"]["added"], 1)
        self.assertEqual(report["text"]["removed"], 1)
        self.assertEqual(report["visual"]["pages"][0]["similarity"], 0.0)
        self.assertEqual(report["visual"]["pages"][1]["similarity"], 100.0)


if __name__ == "__main__":
    unittest.main()
