import YAML from 'yaml';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const get=name=>YAML.parse(readFileSync('.github/workflows/'+name,'utf8'));
const full=get('windows-stool-installer.yml'),legacy=get('windows-desktop-ci.yml');
assert.deepEqual(Object.keys(legacy.on),['workflow_dispatch']);
assert.deepEqual(full.on.push.branches,['build/windows-stool-demo-*']);
assert.ok('workflow_dispatch' in full.on);assert.ok(!('pull_request' in full.on));
assert.deepEqual(Object.keys(full.jobs),['stool-windows-x64']);
const steps=full.jobs['stool-windows-x64'].steps;
assert.ok(!steps.some(s=>s.run?.includes('stool-installer-smoke.ps1')),'Packaging does not repeat functional tests');
assert.ok(steps.some(s=>s.run?.includes('stool-package-manifest.py')));
const acceptance=get('windows-stool-acceptance.yml');
assert.deepEqual(Object.keys(acceptance.on),['workflow_dispatch']);
const acceptanceSteps=acceptance.jobs['accept-existing-candidate'].steps;
assert.ok(acceptanceSteps.some(s=>s.run?.includes('stool-installer-smoke.ps1')));
assert.equal(acceptanceSteps.filter(s=>s.uses?.startsWith('actions/download-artifact@')).length,2);
assert.ok(!acceptanceSteps.some(s=>/tauri.*build|PyInstaller|stage-ocr|stage-office/.test(s.run||'')),'Acceptance reuses existing bytes');
assert.ok(steps.some(s=>s.if==='always()'&&s.uses?.startsWith('actions/upload-artifact@')));
assert.ok(!steps.some(s=>/reader-only|tauri\.reader/.test(s.run||'')));
const fast=get('windows-stool-fast-ci.yml');
const browserStep=fast.jobs['stool-fast'].steps.find(s=>s.name==='Test visible Save controls under production CSP using installed Edge');
assert.ok(browserStep,'Fast CI must retain the grouped installed-Edge browser checks');
assert.match(browserStep.run,/node desktop\/stool-tests\/bookmarks\.browser\.mjs[^\r\n]*\r?\n\s*if \(\$LASTEXITCODE -ne 0\) \{ exit \$LASTEXITCODE \}\r?\n\s*node desktop\/stool-tests\/workflow\.browser\.mjs/,'a failed bookmarks check must stop CI before the workflow check can overwrite its exit code');
assert.match(browserStep.run,/node desktop\/stool-tests\/compare\.browser\.mjs[^\r\n]*\r?\n\s*if \(\$LASTEXITCODE -ne 0\) \{ exit \$LASTEXITCODE \}/,'a failed compare browser check must fail Fast CI');
console.log('Parsed workflow isolation, milestone triggers and durable diagnostics PASS');
