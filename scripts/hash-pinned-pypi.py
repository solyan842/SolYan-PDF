#!/usr/bin/env python3
"""Generate a multi-platform SHA-256 lock from an already pinned PyPI lock.

The input must contain only exact ``name==version`` requirements plus comments/
blank lines. The generator records every SHA-256 distribution digest published
for that exact PyPI release. Installation is intended to use ``--no-deps`` so a
separately sourced dependency such as PaddlePaddle is not re-resolved from PyPI.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

PIN_RE = re.compile(r"^([A-Za-z0-9_.-]+)==([^\s]+)$")


def fetch_hashes(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{urllib.parse.quote(name)}/{urllib.parse.quote(version)}/json"
    request = urllib.request.Request(url, headers={"User-Agent": "SolYan-PDF-lock-generator/1"})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            payload = json.load(response)
    except (urllib.error.URLError, urllib.error.HTTPError) as exc:
        raise RuntimeError(f"Cannot read PyPI metadata for {name}=={version}: {exc}") from exc

    hashes = sorted(
        {
            item.get("digests", {}).get("sha256", "").strip()
            for item in payload.get("urls", [])
            if item.get("digests", {}).get("sha256", "").strip()
        }
    )
    if not hashes:
        raise RuntimeError(f"PyPI returned no SHA-256 distributions for {name}=={version}")
    return hashes


def parse_pins(path: Path) -> list[tuple[str, str]]:
    pins: list[tuple[str, str]] = []
    for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = PIN_RE.fullmatch(line)
        if not match:
            raise RuntimeError(f"{path}:{number}: expected exact name==version pin, got {line!r}")
        pins.append((match.group(1), match.group(2)))
    if not pins:
        raise RuntimeError(f"No pinned requirements found in {path}")
    return pins


def render(pins: list[tuple[str, str]]) -> str:
    out = [
        "# Generated by scripts/hash-pinned-pypi.py",
        "# Every entry is an exact PyPI version with all published SHA-256 distribution hashes.",
        "# Install with pip --require-hashes --no-deps so separately sourced dependencies are not re-resolved.",
    ]
    for name, version in pins:
        hashes = fetch_hashes(name, version)
        out.append(f"{name}=={version} \\")
        for index, digest in enumerate(hashes):
            suffix = " \\" if index < len(hashes) - 1 else ""
            out.append(f"    --hash=sha256:{digest}{suffix}")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    pins = parse_pins(args.input)
    args.output.write_text(render(pins), encoding="utf-8")
    print(f"Wrote {len(pins)} pinned PyPI releases to {args.output}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"error: {exc}", file=sys.stderr)
        raise
