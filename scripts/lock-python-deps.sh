#!/usr/bin/env bash
set -euo pipefail

PYTHON_BIN="${PYTHON_BIN:-python3}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOCK_PIP_VERSION="26.2.1"
SERVICES=(
  backend
  engines/office-service
  engines/sign-service
  engines/archive-service
)

version="$(${PYTHON_BIN} -c 'import sys; print(".".join(map(str, sys.version_info[:3])))')"
if [[ "$version" != "3.13.16" ]]; then
  echo "Expected Python 3.13.16 for lock generation; got ${version}. Set PYTHON_BIN to the exact interpreter." >&2
  exit 2
fi

venv_dir="$(mktemp -d -t solyan-python-lock.XXXXXX)"
trap 'rm -rf "$venv_dir"' EXIT

new_venv() {
  rm -rf "$venv_dir/venv"
  "$PYTHON_BIN" -m venv "$venv_dir/venv"
  py="$venv_dir/venv/bin/python"
  "$py" -m pip install --disable-pip-version-check "pip==${LOCK_PIP_VERSION}"
}

for service in "${SERVICES[@]}"; do
  echo "Locking ${service}"
  new_venv
  "$py" -m pip install --disable-pip-version-check -r "$ROOT/$service/requirements.txt"
  {
    echo '# Generated by scripts/lock-python-deps.sh'
    echo '# Python 3.13.16; regenerate when requirements.txt changes.'
    "$py" -m pip freeze --disable-pip-version-check | LC_ALL=C sort
  } > "$ROOT/$service/requirements.lock"
  "$py" -m pip check
done

ocr_service="engines/ocr-service"
echo "Locking ${ocr_service} with the PaddlePaddle CPU wheel index"
new_venv
"$py" -m pip install --disable-pip-version-check paddlepaddle==3.2.0 -i https://www.paddlepaddle.org.cn/packages/stable/cpu/
"$py" -m pip install --disable-pip-version-check -r "$ROOT/$ocr_service/requirements.txt"
{
  echo '# Generated by scripts/lock-python-deps.sh'
  echo '# Python 3.13.16; PaddlePaddle is locked separately in paddle-requirements.lock to preserve the CPU wheel index.'
  "$py" -m pip freeze --disable-pip-version-check | grep -v '^paddlepaddle==' | LC_ALL=C sort
} > "$ROOT/$ocr_service/requirements.lock"
{
  echo '# Generated by scripts/lock-python-deps.sh'
  echo '# Keep PaddlePaddle on the official CPU wheel index used by the production image.'
  echo '--index-url https://www.paddlepaddle.org.cn/packages/stable/cpu/'
  echo 'paddlepaddle==3.2.0'
} > "$ROOT/$ocr_service/paddle-requirements.lock"
"$py" -m pip check

echo 'Python lockfiles regenerated successfully.'
