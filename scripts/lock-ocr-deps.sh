#!/usr/bin/env bash
set -euo pipefail

PYTHON_BIN="${PYTHON_BIN:-python3}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SERVICE="$ROOT/engines/ocr-service"
PADDLE_INDEX="https://www.paddlepaddle.org.cn/packages/stable/cpu/"
PADDLE_VERSION="3.2.0"

version="$(${PYTHON_BIN} -c 'import sys; print(".".join(map(str, sys.version_info[:3])))')"
if [[ "$version" != "3.13.16" ]]; then
  echo "Expected Python 3.13.16 for OCR lock generation; got ${version}. Set PYTHON_BIN to the exact interpreter." >&2
  exit 2
fi

work="$(mktemp -d -t solyan-ocr-lock.XXXXXX)"
trap 'rm -rf "$work"' EXIT

"$PYTHON_BIN" -m venv "$work/source"
py="$work/source/bin/python"
"$py" -m pip install --disable-pip-version-check --upgrade pip
"$py" -m pip install --disable-pip-version-check "paddlepaddle==${PADDLE_VERSION}" -i "$PADDLE_INDEX"
"$py" -m pip install --disable-pip-version-check -r "$SERVICE/requirements.txt"
"$py" -m pip check

{
  echo '# Generated by scripts/lock-ocr-deps.sh from the real Paddle CPU-index environment.'
  echo '# Python 3.13.16; PaddlePaddle is intentionally stored separately in paddle.lock.'
  "$py" -m pip freeze --disable-pip-version-check | grep -v -E '^paddlepaddle==' | LC_ALL=C sort
} > "$SERVICE/requirements.lock"

cat > "$SERVICE/paddle.lock" <<EOF
# PaddlePaddle wheel source is intentionally explicit and separate from the PyPI graph.
--index-url ${PADDLE_INDEX}
paddlepaddle==${PADDLE_VERSION}
EOF

# Prove the lock model reconstructs without letting Paddle re-resolve dependencies.
"$PYTHON_BIN" -m venv "$work/verify"
verify="$work/verify/bin/python"
"$verify" -m pip install --disable-pip-version-check --upgrade pip
"$verify" -m pip install --disable-pip-version-check -r "$SERVICE/requirements.lock" -r "$SERVICE/requirements.txt"
"$verify" -m pip install --disable-pip-version-check --no-deps -r "$SERVICE/paddle.lock"
"$verify" -m pip check
"$verify" - <<'PY'
import paddle
import paddleocr
print('paddle', paddle.__version__)
print('paddleocr', paddleocr.__name__)
PY

echo 'OCR/Paddle lockfiles regenerated and reconstruction verified.'
